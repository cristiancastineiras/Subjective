// Generates src/shared/theme-defaults.ts from @sub/tokens (palette + themes/light|dark.css) so the theme SDK
// (contrast checks, generator) always starts from the SAME colours the CSS ships. Run: pnpm --filter @sub/core theme-defaults
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const read = (p) => readFileSync(fileURLToPath(new URL(`../../tokens/${p}`, import.meta.url)), 'utf8')
const decls = (css) => Object.fromEntries([...css.matchAll(/(--sub-[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]))
const palette = decls(read('palette.css'))
const light = { ...palette, ...decls(read('themes/light.css')) }
const dark = { ...light, ...decls(read('themes/dark.css')) }

function resolve(vars, name, seen = new Set()) {
  const v = vars[name]
  if (v === undefined || seen.has(name)) throw new Error(`Unknown token ${name}`)
  seen.add(name)
  const m = v.match(/^var\((--[\w-]+)\)$/)
  return m ? resolve(vars, m[1], seen) : v
}

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const keys = Object.keys(decls(read('themes/light.css'))).filter((k) => k.startsWith('--sub-color-') && !k.includes('overlay'))
const out = (vars) => Object.fromEntries(keys.map((k) => [camel(k.replace('--sub-color-', '')), resolve(vars, k)]))

// Component tokens whose default is an expression over other tokens: `--sub-button-radius: var(--sub-control-radius)`.
// A custom property is resolved where it is DECLARED, so overriding the shared token on a descendant does not reach
// these; the SDK re-declares them in the same scope (see deriveTokens).
const componentDefaults = {}
const dir = fileURLToPath(new URL('../../tokens/components/', import.meta.url))
for (const f of readdirSync(dir).filter((f) => f.endsWith('.css') && f !== 'index.css')) {
  for (const [, name, value] of readFileSync(dir + f, 'utf8').matchAll(/(--sub-[\w-]+)\s*:\s*([^;]+);/g)) {
    if (value.includes('var(')) componentDefaults[name] = value.trim()
  }
}

// ---- density: the shared tokens that change, and every component token that derives from them -------------------
// Compact keeps text size (16px minimum) and shrinks space and targets (32px, still above WCAG 2.5.8's 24px AA minimum).
const compactShared = {
  '--sub-target-size': '2rem',
  '--sub-control-min-size': '2rem',
  '--sub-control-padding-block': 'var(--sub-space-1)',
  '--sub-control-padding-inline': 'var(--sub-space-2)',
  '--sub-control-gap': 'var(--sub-space-1)',
  '--sub-target-gap': 'var(--sub-space-1)',
  '--sub-surface-padding': 'var(--sub-space-3)',
  '--sub-label-gap': 'var(--sub-space-1)',
  '--sub-field-gap': 'var(--sub-space-4)',
  '--sub-section-gap': 'var(--sub-space-8)',
}
const semantic = decls(read('semantic.css'))
const comfortableShared = Object.fromEntries(Object.keys(compactShared).map((k) => [k, semantic[k]]))
for (const [k, v] of Object.entries(comfortableShared)) if (v === undefined) throw new Error(`semantic.css has no ${k}`)
const known = new Set(Object.keys(compactShared))
const derived = {}
for (let grew = true; grew; ) {
  grew = false
  for (const [name, expr] of Object.entries(componentDefaults)) {
    if (known.has(name)) continue
    if ([...expr.matchAll(/var\((--[\w-]+)/g)].some((m) => known.has(m[1]))) {
      known.add(name)
      derived[name] = expr
      grew = true
    }
  }
}
const block = (selector, tokens) => `${selector} {\n${Object.entries(tokens).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}`
const densityCss = `/* GENERATED by @sub/core scripts/gen-theme-defaults.mjs. Do not edit by hand.
 * Density: <html data-sub-density="compact">, any element with data-sub-density="compact" (or density="compact"):
 * every component inside gets smaller targets and tighter spacing. A custom property resolves where it is declared,
 * so the component tokens derived from the shared ones are re-declared in the same scope. */
${block(`[data-sub-density='compact'],\n[density='compact']`, { ...compactShared, ...derived })}

${block(`[data-sub-density='comfortable'],\n[density='comfortable']`, { ...comfortableShared, ...derived })}
`
writeFileSync(fileURLToPath(new URL('../../tokens/density.css', import.meta.url)), densityCss)

const body = `// GENERATED by scripts/gen-theme-defaults.mjs from @sub/tokens. Do not edit by hand.
export const defaultColors = {
  light: ${JSON.stringify(out(light), null, 2).replace(/\n/g, '\n  ')},
  dark: ${JSON.stringify(out(dark), null, 2).replace(/\n/g, '\n  ')},
} as const

export type ColorKey = keyof (typeof defaultColors)['light']

export const componentTokenDefaults: Record<string, string> = ${JSON.stringify(componentDefaults, null, 2)}

/** Shared tokens the compact density changes (the derived component tokens are re-declared by deriveTokens) */
export const densityTokens: Record<'compact' | 'comfortable', Record<string, string>> = ${JSON.stringify({ compact: compactShared, comfortable: comfortableShared }, null, 2)}
`
writeFileSync(fileURLToPath(new URL('../src/shared/theme-defaults.ts', import.meta.url)), body)
console.log(`${keys.length} colour tokens x 2 modes -> src/shared/theme-defaults.ts; density.css: ${Object.keys(compactShared).length} shared + ${Object.keys(derived).length} derived tokens`)
