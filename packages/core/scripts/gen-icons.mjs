// Generates src/shared/material-icons.ts from icons.config.json using the official
// Material Symbols SVGs (@material-symbols/svg-400, Apache-2.0). Run: pnpm --filter @sub/core icons
//
// Every icon is its own export (`iconChevronRight()`), so a bundler keeps only the icons a component
// really draws. The name -> path catalogue (`materialIcons`) is a separate export that only the
// components taking an icon NAME (<sub-icon name>, <sub-icon-button icon>) import.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

const root = fileURLToPath(new URL('..', import.meta.url))
const config = JSON.parse(readFileSync(join(root, 'icons.config.json'), 'utf8'))
const pkg = dirname(createRequire(import.meta.url).resolve('@material-symbols/svg-400/package.json'))

/** Mirrored in right-to-left layouts (they point in the reading direction) */
const DIRECTIONAL = new Set(config.directional ?? [])

const paths = {}
const missing = []
for (const name of [...new Set(config.icons)].sort()) {
  const file = join(pkg, config.style, `${name}.svg`)
  if (!existsSync(file)) {
    missing.push(name)
    continue
  }
  const d = [...readFileSync(file, 'utf8').matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]).join(' ')
  paths[name] = d
}
if (missing.length) {
  console.error(`Unknown Material Symbols (${config.style}): ${missing.join(', ')}`)
  process.exit(1)
}
for (const [alias, target] of Object.entries(config.aliases)) {
  if (!paths[target]) {
    console.error(`Alias "${alias}" points to "${target}", which is not in "icons"`)
    process.exit(1)
  }
}
for (const name of DIRECTIONAL) {
  if (!paths[name]) {
    console.error(`Directional icon "${name}" is not in "icons"`)
    process.exit(1)
  }
}

/** `check_circle-fill` -> `iconCheckCircleFill` */
const exportName = (name) => `icon${name.split(/[_-]/).map((p) => p[0].toUpperCase() + p.slice(1)).join('')}`
const names = Object.keys(paths)
const seen = new Map()
for (const name of names) {
  const id = exportName(name)
  if (seen.has(id)) {
    console.error(`"${name}" and "${seen.get(id)}" would both be exported as ${id}`)
    process.exit(1)
  }
  seen.set(id, name)
}

const lines = [
  '// GENERATED by scripts/gen-icons.mjs from icons.config.json. Do not edit by hand.',
  `// Material Symbols (${config.style}, weight 400) by Google, Apache-2.0. 960x960 grid, viewBox "0 -960 960 960".`,
  '//',
  '// One export per icon: import the ones you draw (`iconClose()`) and the bundler drops the rest.',
  '// `materialIcons` (name -> path) is only for components that take an icon NAME at runtime.',
  '',
  "import { svgIcon } from './icon-svg'",
  '',
  ...names.map((name, i) => `const d${i} = ${JSON.stringify(paths[name])} // ${name}`),
  '',
  ...names.map((name, i) => `/** ${name}${DIRECTIONAL.has(name) ? ' (mirrored right-to-left)' : ''} */\nexport const ${exportName(name)} = () => svgIcon(d${i}${DIRECTIONAL.has(name) ? ', true' : ''})`),
  '',
  '/** Every shipped icon by name (path data). Importing it ships all of them. */',
  'export const materialIcons = {',
  ...names.map((name, i) => `  ${JSON.stringify(name)}: d${i},`),
  '} as const',
  '',
  'export const iconAliases = {',
  ...Object.entries(config.aliases).map(([alias, target]) => `  ${alias}: ${JSON.stringify(target)},`),
  '} as const',
  '',
  '/** Names mirrored in right-to-left layouts */',
  `export const directionalIcons: ReadonlySet<string> = /* @__PURE__ */ new Set(${JSON.stringify([...DIRECTIONAL].sort())})`,
  '',
]
writeFileSync(join(root, 'src/shared/material-icons.ts'), lines.join('\n'))
console.log(`${names.length} icons + ${Object.keys(config.aliases).length} aliases -> src/shared/material-icons.ts`)
